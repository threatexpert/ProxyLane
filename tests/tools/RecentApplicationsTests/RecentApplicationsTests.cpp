static void TestCatalogIntegration(Fixture& f)
{
	Entry recent = Item(700);
	InstalledApplications::Application catalog = recent.app;
	catalog.path.MakeUpper();
	Check(MatchesCatalog(recent, catalog), "catalog/recent path dedup");
	recent.available = FALSE;
	Check(!MatchesCatalog(recent, catalog), "unavailable recent must not hide usable catalog target");
	recent.available = TRUE;
	catalog.arguments += L" --different";
	Check(!MatchesCatalog(recent, catalog), "different arguments remain available");
	catalog = recent.app; recent.app.workingDirectory = L"C:/Example/";
	Check(MatchesCatalog(recent, catalog), "missing catalog cwd matches recent metadata");
	catalog.workingDirectory = L"c:\\example";
	Check(MatchesCatalog(recent, catalog), "cwd normalization matches");
	catalog.workingDirectory = L"C:\\Other";
	Check(!MatchesCatalog(recent, catalog), "different explicit cwd preserved");
	recent.app.aumid = L"Example_family!App"; catalog = recent.app; catalog.path.Empty();
	Check(MatchesCatalog(recent, catalog), "packaged target identified by AUMID");
	catalog.aumid = L"Other_family!App";
	Check(!MatchesCatalog(recent, catalog), "different AUMID preserved");
	Seed(f.Path(L"validated.ini"));
	Store store(L"A", f.Path(L"validated.ini"));
	Check(store.Remember(Item(700)), "validation fixture existing target");
	Entry missing = Item(701); missing.app.path = f.Path(L"missing.exe");
	Check(store.Remember(missing), "validation fixture missing target");
	CString identity; Check(EnsureProfileId(L"A", identity, f.Path(L"validated.ini")), "validation ID");
	Load* load = BeginLoad(L"A", f.Path(L"validated.ini"), identity);
	BOOL done = FALSE;
	const DWORD started = GetTickCount();
	while (!done && GetTickCount() - started < 10000)
	{
		EnterCriticalSection(&load->lock); done = load->done; LeaveCriticalSection(&load->lock);
		if (!done) Sleep(10);
	}
	const BOOL valid = done && load->succeeded && load->entries.size() == 2 &&
		!load->entries[1].available && load->entries[1].app.path == missing.app.path &&
		load->entries[1].app.name == missing.app.name && !load->entries[1].id.IsEmpty() &&
		load->entries[0].available && load->entries[0].app.arguments == Item(700).app.arguments;
	if (load->cancel) SetEvent(load->cancel);
	load->Release();
	Check(valid, "background validation retains missing targets as unavailable");
	std::vector<Entry> saved;
	Check(store.Read(saved) && saved.size() == 2, "validation does not permanently erase inaccessible entries");
	Check(saved[0].available, "availability is transient and rechecked on reload");
	Check(store.Remove(saved[0].id), "unavailable entry can be explicitly removed");
	Check(store.Read(saved) && saved.size() == 1 && saved[0].app.arguments == Item(700).app.arguments,
		"removing unavailable entry preserves usable history");
	std::cout << "catalog merge identity and background validation: PASS\n";
}


static BOOL WaitForLoad(Load* load)
{
 const DWORD started = GetTickCount();
 for (;;)
 {
  EnterCriticalSection(&load->lock); const BOOL done = load->done; LeaveCriticalSection(&load->lock);
  if (done) return load->succeeded;
  if (GetTickCount() - started > 10000) return FALSE;
  Sleep(10);
 }
}

// Hold the real history mutex to make the warmup deterministically pending.
struct HistoryGate
{
 HANDLE mutex;
 explicit HistoryGate(const CString& path)
 {
  WCHAR absolute[32768]; GetFullPathName(path, _countof(absolute), absolute, NULL);
  CString key(absolute); key.Replace(L'/', L'\\'); key.MakeLower();
  ULONGLONG hash = 14695981039346656037ULL;
  for (int i = 0; i < key.GetLength(); ++i) { hash ^= static_cast<WORD>(key[i]); hash *= 1099511628211ULL; }
  CString name; name.Format(L"Global\\ProxyLane.RecentIni.%016I64x", hash);
  mutex = CreateMutex(NULL, FALSE, name);
  Check(mutex && WaitForSingleObject(mutex, 1000) == WAIT_OBJECT_0, "lock cache fixture");
 }
 ~HistoryGate() { ReleaseMutex(mutex); CloseHandle(mutex); }
};

static void CheckDisplaySnapshot(Load* load, const std::vector<CString>& expected)
{
	Check(load && load->succeeded && load->entries.size() == expected.size(), "display snapshot size");
	std::vector<Entry> picker, home;
	Clone(load->entries, picker);
	Clone(load->entries, home, 2); // A compact consumer must limit AFTER shared ordering.
	BOOL same = TRUE;
	for (size_t i = 0; i < picker.size(); ++i) same = same && picker[i].id == expected[i];
	for (size_t i = 0; i < home.size(); ++i) same = same && home[i].id == expected[i];
	ReleaseIcons(picker); ReleaseIcons(home);
	Check(same, "picker/home get identical order without local sorting");
}

static void TestSharedDisplayOrder(Fixture& f)
{
	const CString path = f.Path(L"shared-order.ini"); Seed(path);
	Store store(L"A", path);
	for (int i = 0; i < 3; ++i) Check(store.Remember(Item(i)), "shared display seed");
	CString identity; Check(EnsureProfileId(L"A", identity, path), "shared display identity");
	Load* load = AcquireLoad(L"A", path, identity);
	Check(WaitForLoad(load) && load->entries.size() == 3, "cold display load");
	std::vector<CString> expected;
	for (int i = 0; i < 3; ++i)
	{
		Check(load->entries[i].app.arguments == Item(i).app.arguments, "new apps append in cold snapshot");
		expected.push_back(load->entries[i].id);
	}
	CheckDisplaySnapshot(load, expected);
	load->Release();
	Load* ready = AcquireReadyLoad(L"A", path, identity);
	CheckDisplaySnapshot(ready, expected); ready->Release();
	// Launch the last entry, both via fresh catalog metadata and a saved record.
	for (int launch = 0; launch < 2; ++launch)
	{
		std::vector<Entry> saved;
		Check(store.Read(saved), "read launch history");
		Entry entry = Item(2);
		if (launch) for (const auto& row : saved) if (row.id == expected.back()) entry = row;
		Check(store.Remember(entry), "record launch without changing placement");
		Check(store.Read(saved) && saved[0].id == expected.back(), "usage timestamp updates internally");
		ready = AcquireReadyLoad(L"A", path, identity);
		CheckDisplaySnapshot(ready, expected); ready->Release();
		load = AcquireLoad(L"A", path, identity);
		Check(WaitForLoad(load), "post-launch validation"); CheckDisplaySnapshot(load, expected); load->Release();
	}
	const CString moved = expected.back();
	Check(store.Move(moved, -1), "manual move publishes shared order");
	std::swap(expected[1], expected[2]);
	ready = AcquireReadyLoad(L"A", path, identity);
	CheckDisplaySnapshot(ready, expected); ready->Release();
	Check(store.Remember(Item(2)), "launch manually positioned entry");
	ready = AcquireReadyLoad(L"A", path, identity);
	CheckDisplaySnapshot(ready, expected); ready->Release();
	// A fresh validation task has the same order as the warm cache/reopened picker.
	load = BeginLoad(L"A", path, identity);
	Check(WaitForLoad(load), "fresh reload after manual move"); CheckDisplaySnapshot(load, expected); load->Release();
	Check(store.SetPinned(moved, TRUE), "explicit pin still reorders");
	std::swap(expected[0], expected[1]);
	ready = AcquireReadyLoad(L"A", path, identity);
	CheckDisplaySnapshot(ready, expected); ready->Release();
	Check(store.Remember(Item(0)), "ordinary launch cannot outrank explicit pin");
	load = AcquireLoad(L"A", path, identity);
	Check(WaitForLoad(load), "pinned display validation"); CheckDisplaySnapshot(load, expected); load->Release();
	InvalidateCache(path, identity, TRUE);
	std::cout << "shared picker/home order: cold/warm/reload, catalog/recent launch, manual move and pin: PASS\n";
}

static void TestCache(Fixture& f)
{
 const CString path = f.Path(L"cache.ini"); Seed(path);
 Store store(L"A", path); Check(store.Remember(Item(800)), "cache seed");
 CString id; Check(EnsureProfileId(L"A", id, path), "cache profile ID");
 Load *old = NULL, *latest = NULL;
 {
  HistoryGate gate(path);
  Preload(L"A", path); // Also exercises read-only selected-profile discovery.
  old = AcquireLoad(L"A", path, id);
  EnterCriticalSection(&old->lock); BOOL pending = !old->done; LeaveCriticalSection(&old->lock);
  Check(pending, "warmup still pending when picker opens");
  Load* reopened = AcquireLoad(L"A", path, id);
  Check(reopened == old, "opening during warmup shares task");
  reopened->Release(); // Close the picker; the cache and worker must survive.
  Check(WaitForSingleObject(old->cancel, 0) == WAIT_TIMEOUT, "closing subscriber does not cancel warmup");
  reopened = AcquireLoad(L"A", path, id);
  Check(reopened == old, "reopening does not restart warmup"); reopened->Release();
  Check(store.Remember(Item(801)), "edit while old validation is pending");
  Check(!IsCurrentLoad(old), "old generation invalidated before it can publish");
  latest = AcquireLoad(L"A", path, id);
  Check(latest != old, "modified history receives a new generation");
 }
 Check(WaitForLoad(latest) && latest->entries.size() == 2, "latest generation contains both entries");
 Check(WaitForLoad(old) && !IsCurrentLoad(old), "late old result cannot replace new generation");
 old->Release();
 Load* ready = AcquireReadyLoad(L"A", path, id);
 Check(ready == latest, "ready snapshot published without picker ownership");
 std::vector<Entry> clone; Clone(ready->entries, clone);
 Check(clone.size() == 2 && ready->entries.size() == 2, "consuming snapshot never drains shared entries");
 for (size_t i = 0; i < clone.size(); ++i)
  Check(!ready->entries[i].app.icon || (clone[i].app.icon && clone[i].app.icon != ready->entries[i].app.icon), "icons independently owned");
 ReleaseIcons(clone);
 const CString removed = ready->entries[0].id;
 ready->Release();
 Check(store.Remove(removed), "remove cached recent");
 ready = AcquireReadyLoad(L"A", path, id);
 Check(ready && ready->entries.size() == 1 && ready->entries[0].id != removed, "removal published before background validation");
 ready->Release(); latest->Release();
 latest = AcquireLoad(L"A", path, id);
 Check(WaitForLoad(latest) && latest->entries.size() == 1, "validation preserves local removal");
 Seed(path, L"B"); Check(Store(L"B", path).Remember(Item(900)), "second profile fixture");
 CString otherId; EnsureProfileId(L"B", otherId, path);
 Load* other = AcquireLoad(L"B", path, otherId);
 Check(WaitForLoad(other) && other->entries.size() == 1 && other->entries[0].app.arguments == Item(900).app.arguments,
  "profiles never share recent entries"); other->Release();
 Check(DeleteProfile(L"A", path), "delete cached profile");
 Check(!AcquireReadyLoad(L"A", path, id) && !IsCurrentLoad(latest), "deleting profile removes its cached snapshots");
 latest->Release();
 // Bound snapshots while already-open consumers retain valid references.
 for (int i = 0; i < 5; ++i)
 {
  CString name; name.Format(L"P%d", i); Seed(path, name);
  CString identity; EnsureProfileId(name, identity, path);
  Load* load = AcquireLoad(name, path, identity); Check(WaitForLoad(load), "bounded profile cache load"); load->Release();
 }
 Check(!AcquireReadyLoad(L"B", path, otherId), "least-recently-used profile evicted");
 std::cout << "recent cache warmup, close/reopen, generations, profile isolation and eviction: PASS\n";
}

