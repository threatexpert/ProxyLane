"""Build a relocation-free ARM64 COFF .text section into a deterministic header."""
import argparse
import pathlib
import struct
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = ROOT / 'src/remotecode/arm64/BootstrapBytes.h'


def build(clang):
    with tempfile.TemporaryDirectory(prefix='proxylane-arm64-') as directory:
        obj = pathlib.Path(directory) / 'bootstrap.obj'
        subprocess.run([clang, '--target=aarch64-pc-windows-msvc', '-c',
                        str(ROOT / 'src/remotecode/arm64/Bootstrap.S'), '-o', str(obj)], check=True)
        data = obj.read_bytes()
    machine, count, _, symbols, symbol_count, optional, _ = struct.unpack_from('<HHIIIHH', data)
    if machine != 0xaa64 or optional:
        raise ValueError('Expected ARM64 COFF')
    sections = []
    for i in range(count):
        section = struct.unpack_from('<8sIIIIIIHHI', data, 20 + i * 40)
        sections.append(section)
    index, section = next((i + 1, s) for i, s in enumerate(sections) if s[0].rstrip(b'\0') == b'.text')
    if section[7] or section[9] & 0x01000000:
        raise ValueError('Bootstrap contains relocations')
    code = data[section[4]:section[4] + section[3]]
    strings = symbols + symbol_count * 18
    labels = {}
    i = 0
    while i < symbol_count:
        name, value, sec, _, _, aux = struct.unpack_from('<8sIhHBB', data, symbols + i * 18)
        if name[:4] == b'\0' * 4:
            start = strings + struct.unpack_from('<I', name, 4)[0]
            name = data[start:data.index(b'\0', start)]
        else:
            name = name.rstrip(b'\0')
        if sec == index:
            labels[name.decode()] = value
        i += 1 + aux
    return code, {key: labels['Bootstrap' + key] for key in ('Startup', 'Thread', 'ParameterAddress')}


def render(code, labels):
    lines = ['// Generated by scripts/generate-arm64-bootstrap.py; do not edit.',
             '#pragma once', 'namespace Arm64Bootstrap {']
    lines += ['static const unsigned int %sOffset = %d;' % pair for pair in labels.items()]
    lines += ['static const unsigned char Code[] = {']
    lines += ['    ' + ', '.join('0x%02x' % b for b in code[i:i + 16]) + ','
              for i in range(0, len(code), 16)]
    return '\n'.join(lines + ['};', '}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clang', default='clang')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    code, labels = build(args.clang)
    content = render(code, labels)
    if args.check:
        if HEADER.read_text(encoding='utf-8') != content:
            raise SystemExit('BootstrapBytes.h is stale; regenerate it')
    else:
        HEADER.write_text(content, encoding='utf-8', newline='\n')
    print('ARM64 bootstrap: %d bytes, no relocations, %s' % (len(code), labels))
