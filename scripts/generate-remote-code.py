"""Compile the loader and extract relocation-free x86/x64 .text (VS 2019).

Run after changing remoteCode.cpp or its ABI. --check verifies committed bytes.
No executable is run during generation; COFF relocations are rejected.
"""
import argparse
import os
from pathlib import Path
import struct
import subprocess


def extract(path, machine):
    data = path.read_bytes()
    actual, sections, _, _, _, optional, _ = struct.unpack_from('<HHLLLHH', data)
    if actual != machine:
        raise RuntimeError('Unexpected COFF architecture')
    code = []
    for index in range(sections):
        offset = 20 + optional + 40 * index
        name, _, _, size, raw, _, _, relocations, _, flags = struct.unpack_from('<8sLLLLLLHHL', data, offset)
        if flags & 0x20 and size:
            if relocations:
                raise RuntimeError(f'{name!r} contains external references/relocations')
            code.append(data[raw:raw + size])
    if len(code) != 1:
        raise RuntimeError(f'Expected one standalone code section, found {len(code)}')
    return code[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--vcvars', default=r'C:\Program Files (x86)\Microsoft Visual Studio\2019\Professional\VC\Auxiliary\Build\vcvarsall.bat')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    work = root / 'build' / 'loader-diagnostics'
    work.mkdir(parents=True, exist_ok=True)
    for arch, machine in [('x86', 0x14c), ('x64', 0x8664)]:
        obj = work / f'remoteCode.{arch}.obj'
        batch = work / f'generate-{arch}.cmd'
        batch.write_text(
            f'@echo off\ncall "{args.vcvars}" {arch} -vcvars_ver=14.16 >nul\n'
            'if errorlevel 1 exit /b 1\n'
            f'cl /nologo /c /O1 /GS- /GL- /Gy- /GR- /Zl /utf-8 '
            f'/Fo"{obj}" /FAcs /Fa"{work / (arch + ".asm")}" '
            f'"{root / "src/remotecode/remoteCode.cpp"}"\n', encoding='utf-8')
        subprocess.run([os.environ.get('COMSPEC', 'cmd.exe'), '/c', str(batch)], cwd=root, check=True)
        code = extract(obj, machine)
        text = '// Generated by scripts/generate-remote-code.py; do not edit.\n'
        text += f'static const unsigned char sc_ldr[{len(code)}] = {{\n'
        for start in range(0, len(code), 16):
            text += '    ' + ', '.join(f'0x{b:02X}' for b in code[start:start+16]) + ',\n'
        text += '};\n'
        target = root / f'src/remotecode/remoteCode.{arch}.inc'
        if args.check:
            if target.read_text() != text:
                raise RuntimeError(f'{target} is stale')
        else:
            target.write_text(text, encoding='utf-8', newline='\n')
        print(f'{arch}: {len(code)} bytes, no relocations')


if __name__ == '__main__':
    main()
